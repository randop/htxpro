use std::collections::HashMap;

/// Identity established by a configured security module.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct AuthIdentity {
    pub module: String,
    pub subject: String,
    pub email: Option<String>,
    pub name: Option<String>,
}

#[derive(Debug, Clone)]
pub struct HttpRequest {
    pub method: String,
    pub authority: String,
    /// Absolute-path component only; query is held separately.
    pub path: String,
    pub query: Option<String>,
    pub headers: HashMap<String, String>,
    pub body: Vec<u8>,
    pub body_too_large: bool,
    /// Populated by the configured security module after successful authentication.
    pub auth: Option<AuthIdentity>,
}

#[derive(Debug, Clone)]
pub struct HttpResponse {
    pub status: u16,
    pub content_type: String,
    pub cache_control: Option<String>,
    /// Additional application-generated headers such as `location` or `set-cookie`.
    pub headers: Vec<(String, String)>,
    pub body: Vec<u8>,
    pub head_only: bool,
}

impl HttpResponse {
    pub fn new(status: u16, content_type: impl Into<String>, body: impl Into<Vec<u8>>) -> Self {
        Self {
            status,
            content_type: content_type.into(),
            cache_control: None,
            headers: Vec::new(),
            body: body.into(),
            head_only: false,
        }
    }

    pub fn json(status: u16, value: serde_json::Value) -> Self {
        let body = serde_json::to_vec(&value)
            .unwrap_or_else(|_| b"{\"error\":\"serialization failed\"}".to_vec());
        let mut response = Self::new(status, "application/json; charset=utf-8", body);
        response.cache_control = Some("no-store".to_owned());
        response
    }

    pub fn error(status: u16, message: &str) -> Self {
        Self::json(status, serde_json::json!({ "error": message }))
    }

    pub fn with_cache(mut self, value: impl Into<String>) -> Self {
        self.cache_control = Some(value.into());
        self
    }

    pub fn with_header(mut self, name: impl Into<String>, value: impl Into<String>) -> Self {
        self.headers.push((name.into(), value.into()));
        self
    }

    pub fn with_cookie(self, value: impl Into<String>) -> Self {
        self.with_header("set-cookie", value)
    }

    pub fn redirect(status: u16, location: impl Into<String>) -> Self {
        Self::new(status, "text/html; charset=utf-8", Vec::<u8>::new())
            .with_header("location", location)
            .with_cache("no-store")
    }

    pub fn not_found() -> Self {
        Self::error(404, "not found")
    }
}

/// Headers whose values are generated by protocol writers and must not be
/// overridden by application responses.
pub(crate) fn is_reserved_response_header(name: &str) -> bool {
    matches!(
        name.to_ascii_lowercase().as_str(),
        "content-length"
            | "content-type"
            | "cache-control"
            | "transfer-encoding"
            | "connection"
            | "keep-alive"
            | "server"
            | "alt-svc"
            | "x-content-type-options"
    )
}

pub(crate) fn is_safe_header(name: &str, value: &str) -> bool {
    !is_reserved_response_header(name)
        && !name.is_empty()
        && name.bytes().all(|byte| {
            byte.is_ascii_alphanumeric()
                || matches!(
                    byte,
                    b'!' | b'#'
                        | b'$'
                        | b'%'
                        | b'&'
                        | b'\''
                        | b'*'
                        | b'+'
                        | b'-'
                        | b'.'
                        | b'^'
                        | b'_'
                        | b'`'
                        | b'|'
                        | b'~'
                )
        })
        && !value
            .chars()
            .any(|character| character.is_control() && character != '\t')
}

#[cfg(test)]
mod tests {
    use super::is_safe_header;

    #[test]
    fn response_header_filter_allows_cookies_and_rejects_injection() {
        assert!(is_safe_header("location", "/dashboard"));
        assert!(is_safe_header("set-cookie", "session=abc; Path=/"));
        assert!(!is_safe_header("content-length", "0"));
        assert!(!is_safe_header("cache-control", "public"));
        assert!(!is_safe_header("x-bad", "value\r\nInjected: yes"));
        assert!(!is_safe_header("bad name", "value"));
    }
}
